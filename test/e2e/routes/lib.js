/// No account in [names] may hold a live call membership in [roomId] before a
/// route starts. A leftover from an earlier route is waited out (the server's
/// delayed leave clears a dead device), never written over.
async function waitNoLiveCall(names, roomId, { timeoutS = 120 } = {}) {
  const deadline = Date.now() + timeoutS * 1000;
  for (;;) {
    const live = [];
    for (const n of names) {
      const a = cfg.accounts[n];
      const { token, userId } = await mx.login(a.user, a.pass);
      try {
        const d = await mx.liveMembershipDevices(token, roomId, userId);
        if (d.length) live.push(`${n}:${d.join(',')}`);
      } finally {
        await mx.logout(token).catch(() => {});
      }
    }
    if (!live.length) return;
    if (Date.now() > deadline) throw new Error(`stale live call memberships before the route: ${live.join(' ')}`);
    console.log(`   (waiting out stale memberships: ${live.join(' ')})`);
    await wait(10000);
  }
}

