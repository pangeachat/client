/// Places a call from [A] and answers it on [B]; returns the ring and the call
/// key, or null after recording why.
async function placeAndAnswer(s, A, B, roomId, { video = false, answer = true } = {}) {
  const mark = await h.mark(A.token, roomId);
  const rang = await h.actUntil('place call',
    async () => { await h.ensureRoom(A, A.roomLocalpart); await ui.clickControl(A.page, 'call').catch(() => {}); },
    async () => (await h.since(A.token, roomId, mark)).some((e) => e.type === mx.RING && e.sender === A.userId),
    { tries: 4, gap: 4000 });
  h.check(s, 'the call rang', rang, 'no ring event from the caller');
  if (!rang) return null;
  const ring = (await h.since(A.token, roomId, mark)).find((e) => e.type === mx.RING && e.sender === A.userId);
  const callKey = ring?.content?.['m.relates_to']?.event_id || null;
  const ringAt = Date.now();
  if (!answer) return { mark, ring, callKey, ringAt };
  const joined = await h.actUntil('answer', () => ui.clickBanner(B.page, 'answer'),
    () => mx.hasMembership(B.token, roomId, B.userId));
  h.check(s, 'the callee answered (membership published)', joined, 'no callee membership');
  if (!joined) return null;
  const answeredAt = Date.now();
  // The chat header offers voice only (#8793); a video call is a call whose
  // camera is turned on from the call panel, on both sides.
  if (video) for (const p of [A, B]) await cameraOn(s, p);
  return { mark, ring, callKey, ringAt, answeredAt };
}

async function cameraOn(s, p) {
  const offLabels = L('callCameraOff');
  let on = false;
  for (let i = 0; i < 4 && !on; i++) {
    await ui.clickPanel(p.page, 'camera').catch(() => {});
    await wait(2500);
    const l = await ui.labels(p.page).catch(() => []);
    on = l.some((x) => offLabels.includes(x) || /camera off/i.test(x));
  }
  h.check(s, `${p.name} turned the camera on`, on, 'the panel never offered "turn camera off"');
  return on;
}

async function hangUp(s, P, roomId) {
  const left = await h.actUntil('hangup', () => ui.clickPanel(P.page, 'hangup'),
    async () => !(await mx.hasMembership(P.token, roomId, P.userId)), { tries: 6, gap: 3000 });
  h.check(s, `${P.name} hung up (membership gone)`, left, 'membership still live');
  return left;
}

/// Every event related to the call key (the halves, the recordings, the
/// merged recording, the clock all hang off it).
async function related(token, roomId, callKey, relType) {
  const out = [];
  let from = null;
  for (let page = 0; page < 10; page++) {
    const q = from ? `?from=${encodeURIComponent(from)}&limit=100` : '?limit=100';
    const res = await mx.api(`/_matrix/client/v1/rooms/${encodeURIComponent(roomId)}/relations/${encodeURIComponent(callKey)}/${relType}${q}`, { token });
    out.push(...(res.chunk || []));
    if (!res.next_batch) break;
    from = res.next_batch;
  }
  return out;
}

/// Everything of [types] after [mark], far enough back that a call's
/// membership churn cannot push it out of the window.
async function eventsSince(token, roomId, mark, types) {
  const out = [];
  let from = null;
  for (let page = 0; page < 6; page++) {
    const r = await mx.messagesBack(token, roomId, { from, limit: 200 });
    const chunk = r.chunk || [];
    let hit = false;
    // A backwards page is newest-first: walk it in that order and stop AT the
    // mark, so what is kept is everything newer than it.
    for (const e of chunk) {
      if (e.event_id === mark) { hit = true; break; }
      if (!types || types.includes(e.type)) out.push(e);
    }
    if (hit || !r.end || !chunk.length) break;
    from = r.end;
  }
  return out.reverse();
}

const spoken = (ev) => (Array.isArray(ev?.content?.segments) ? ev.content.segments : [])
