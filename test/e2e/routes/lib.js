async function finish(s, participants, extraInfo = {}) {
  const all = [...participants, ...(extraInfo.closed || [])].filter(Boolean);
  for (const p of all) await Promise.all(p.sttPending || []).catch(() => {});
  const cost = sttCost(all);
  save('stt-cost.json', { ...cost, calls: all.flatMap((p) => (p.sttCalls || []).map((c) => ({ who: p.name, ...c }))) });
  console.log(`   STT: ${cost.calls} request(s), ${cost.seconds}s of audio, ~$${cost.usd} (${cost.services.join(',')})`);
  delete extraInfo.closed;
  extraInfo.stt = cost;
  for (const p of all) {
    if (participants.includes(p)) await saveParticipant(p).catch(() => {});
    h.check(s, `${p.name} had no unhandled page errors`, p.errors.length === 0, JSON.stringify(p.errors.slice(0, 2)));
    h.check(s, `${p.name}'s recorder logged no capture failure`, (p.recorderWarnings || []).length === 0, JSON.stringify((p.recorderWarnings || []).slice(0, 2)));
  }
  const unproven = h.report();
  const failed = h.results.filter((r) => !r.pass);
  save('result.json', {
    route: s, at: new Date().toISOString(), ...extraInfo,
    pass: unproven === 0,
    checks: h.results, skipped: h.inconclusive,
    failing: failed.map((f) => `${f.name}: ${f.detail}`),
  });
  for (const p of participants) await p?.browser?.close().catch(() => {});
  process.exit(unproven === 0 ? 0 : 1);
}

function fatal(s, participants) {
  return async (e) => {
    console.error('ROUTE ERROR', e && e.stack ? e.stack : e);
    h.skipped(s, 'the route ran to completion', `harness/route error: ${String(e && e.message ? e.message : e).slice(0, 300)}`);
    await finish(s, participants.filter(Boolean));
  };
}

