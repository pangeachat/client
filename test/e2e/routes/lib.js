/// Downloads an mxc and asks ffprobe/ffmpeg whether it decodes, how long it is
/// and whether it holds sound. "Plays back" is asked of the file the player
/// would fetch; the in-app player itself is checked by its control label.
async function probeMedia(token, mxc, tag) {
  const m = /^mxc:\/\/([^/]+)\/(.+)$/.exec(mxc || '');
  if (!m) return { ok: false, why: `not an mxc: ${mxc}` };
  const res = await fetch(`${cfg.homeserver}/_matrix/client/v1/media/download/${m[1]}/${m[2]}`, { headers: { authorization: `Bearer ${token}` } });
  if (!res.ok) return { ok: false, why: `download ${res.status}` };
  const buf = Buffer.from(await res.arrayBuffer());
  const f = path.join(evidenceDir(), `media-${tag}`);
  fs.writeFileSync(f, buf);
  const { spawnSync } = require('child_process');
  const probe = spawnSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f], { encoding: 'utf8' });
  const duration = Number(String(probe.stdout || '').trim());
  if (probe.status !== 0 || !Number.isFinite(duration)) return { ok: false, bytes: buf.length, why: `does not decode: ${String(probe.stderr).slice(0, 200)}` };
  // ffmpeg prints volumedetect to STDERR.
  const vd = spawnSync('ffmpeg', ['-v', 'info', '-nostats', '-i', f, '-af', 'volumedetect', '-f', 'null', '-'], { encoding: 'utf8' });
  const md = /mean_volume: (-?(?:[\d.]+|inf)) dB/.exec(String(vd.stderr || ''));
  const meanDb = md ? (md[1] === '-inf' ? -Infinity : Number(md[1])) : null;
  if (vd.status !== 0 || meanDb == null) return { ok: false, bytes: buf.length, duration, why: `volume analysis failed (exit ${vd.status})` };
  return { ok: Number.isFinite(duration) && duration > 0, bytes: buf.length, duration, meanDb, file: f };
}

