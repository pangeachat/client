/// Everything a page says, the network requests it makes, and every media
/// element it plays -- recorded from before the app loads.
async function instrument(page) {
  await page.evaluateOnNewDocument(() => {
    window.__routesMedia = [];
    const log = (kind, el) => {
      try {
        window.__routesMedia.push({ t: Date.now(), kind, src: String(el.currentSrc || el.src || '').slice(-80), at: el.currentTime, dur: el.duration });
      } catch (_) {}
    };
    const origPlay = HTMLMediaElement.prototype.play;
    HTMLMediaElement.prototype.play = function (...a) {
      if (!this.__routesHooked) {
        this.__routesHooked = true;
        for (const ev of ['pause', 'ended', 'error']) this.addEventListener(ev, () => log(ev, this));
      }
      log('play', this);
      return origPlay.apply(this, a);
    };
  });
}

async function openP(name, roomLocalpart, port, { wav } = {}) {
  if (wav) cfg.accounts[name].wav = wav;
  const consoleLines = [];
  const requests = [];
  const sttCalls = [];
  const sttPending = [];
  const p = await h.openParticipant(name, roomLocalpart, port, {
    prepare: async (page) => {
      await instrument(page);
      page.on('console', (m) => consoleLines.push(`${new Date().toISOString()} ${m.type()} ${m.text()}`.slice(0, 3000)));
      page.on('requestfinished', (r) => {
        const u = r.url();
        if (/\/speech_to_text/.test(u) && r.method() === 'POST') sttPending.push(recordStt(r, sttCalls));
        if (/\/(speech_to_text|choreo|stt|transcri|media\/v3\/upload|media\/upload)/i.test(u)) {
          requests.push({ t: Date.now(), method: r.method(), url: u.replace(/access_token=[^&]+/, 'access_token=…'), status: r.response()?.status() });
        }
      });
      page.on('requestfailed', (r) => {
        const u = r.url();
        if (/\/(speech_to_text|media\/v3\/upload|media\/upload|send\/pangea)/i.test(u)) {
          requests.push({ t: Date.now(), method: r.method(), url: u, failed: r.failure()?.errorText });
        }
      });
    },
  });
  p.sttCalls = sttCalls;
  p.sttPending = sttPending;
  p.consoleLines = consoleLines;
  p.requests = requests;
  p.port = port;
  p.roomLocalpart = roomLocalpart;
  return p;
}

// What real speech-to-text this browser asked for: the audio seconds of every
// /speech_to_text request and the provider that answered, so a run can state
// its spend. Prices per audio minute, list price, the dearest tier.
const STT_PRICE_PER_MIN = { openai_whisper_1: 0.006, whisper: 0.006, deepgram: 0.0043, google: 0.016 };
async function recordStt(r, out) {
  const rec = { t: Date.now(), status: r.response()?.status() };
  try {
    const body = await r.fetchPostData();
    const j = JSON.parse(body || '{}');
    const b64 = j.audio_content || j.audioContent || j.audio || '';
    const buf = Buffer.from(String(b64), 'base64');
    const f = path.join(evidenceDir(), `stt-${out.length}-${Date.now()}.audio`);
    fs.writeFileSync(f, buf);
    const { spawnSync } = require('child_process');
    const d = Number(String(spawnSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f], { encoding: 'utf8' }).stdout).trim());
    rec.audioBytes = buf.length;
    rec.seconds = Number.isFinite(d) ? d : null;
    rec.config = j.config ? { lang: j.config.speaker_l2 || j.config.language_code, sample_rate: j.config.sample_rate_hertz } : undefined;
    fs.rmSync(f, { force: true });
  } catch (e) { rec.bodyError = e.message; }
  try {
    const res = await r.response()?.json();
    rec.service = res?.service || (res?.results && res.results[0]?.service) || null;
  } catch (_) { rec.service = null; }
  out.push(rec);
}
function sttCost(participants) {
  const calls = participants.flatMap((p) => (p && p.sttCalls) || []);
  let seconds = 0;
  let usd = 0;
  for (const c of calls) {
    // A refused request (401/403/5xx) reached no provider and cost nothing.
    if (!(c.status >= 200 && c.status < 300)) continue;
    const sec = c.seconds || 0;
    seconds += sec;
    const k = String(c.service || '').toLowerCase();
    const rate = Object.entries(STT_PRICE_PER_MIN).find(([n]) => k.includes(n))?.[1] ?? 0.016;
    usd += (sec / 60) * rate;
  }
  return { calls: calls.length, billable: calls.filter((c) => c.status >= 200 && c.status < 300).length, seconds: Math.round(seconds), usd: Math.round(usd * 10000) / 10000, unknownDuration: calls.filter((c) => c.seconds == null).length, services: [...new Set(calls.map((c) => c.service))] };
}

