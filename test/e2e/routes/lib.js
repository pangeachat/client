/// The construct uses credited against a call, read out of the speaker's
/// analytics room(s). A use carries the call's anchor as `msgId` and a stable
/// `id`, so a credit applied twice shows as the same ids twice.
async function creditsFor(token, userId, anchorIds, sinceTs) {
  const joined = (await mx.api('/_matrix/client/v3/joined_rooms', { token })).joined_rooms || [];
  const uses = [];
  const roomsSeen = [];
  for (const r of joined) {
    let create;
    try {
      create = await mx.api(`/_matrix/client/v3/rooms/${encodeURIComponent(r)}/state/m.room.create/`, { token });
    } catch (_) { continue; }
    if (create.type !== 'p.analytics') continue;
    roomsSeen.push(r);
    let from = null;
    for (let page = 0; page < 5; page++) {
      const res = await mx.messagesBack(token, r, { from, limit: 100 });
      const chunk = res.chunk || [];
      let older = false;
      for (const e of chunk) {
        if (e.origin_server_ts < sinceTs) { older = true; continue; }
        if (e.type !== CONSTRUCT || e.sender !== userId) continue;
        for (const u of (e.content?.uses || [])) {
          if (anchorIds.includes(u.msgId)) uses.push({ event: e.event_id, lemma: u.lemma, type: u.constructType, form: u.form, cat: u.categories, useType: u.useType, ts: u.timeStamp });
        }
      }
      if (older || !res.end || !chunk.length) break;
      from = res.end;
    }
  }
  // A use carries no stable id on the wire (`id` is null for call uses), and
  // one credit is split across several events by size. Two ways a credit can
  // land twice: a second process re-credits (a new credit moment -> a second
  // cluster of timeStamps), or one process sends the same uses again (every
  // use key appears an even number of times). One credit = one cluster, and
  // not every key doubled.
  const tss = [...new Set(uses.map((u) => Date.parse(u.ts)))].sort((x, y) => x - y);
  let clusters = tss.length ? 1 : 0;
  for (let i = 1; i < tss.length; i++) if (tss[i] - tss[i - 1] > 2000) clusters++;
  const counts = {};
  for (const u of uses) { const k = `${u.lemma}|${u.type}|${u.form}|${u.cat}|${u.useType}|${u.ts}`; counts[k] = (counts[k] || 0) + 1; }
  const keys = Object.values(counts);
  const doubled = keys.length > 5 && keys.every((c) => c % 2 === 0);
  // A resent analytics event: two events carrying the same list of uses.
  const perEvent = {};
  for (const u of uses) (perEvent[u.event] = perEvent[u.event] || []).push(`${u.lemma}|${u.type}|${u.form}|${u.cat}|${u.useType}|${u.ts}`);
  const sigs = Object.values(perEvent).map((l) => l.sort().join(','));
  const resentEvents = sigs.length - new Set(sigs).size;
  return { rooms: roomsSeen.length, uses: uses.length, events: [...new Set(uses.map((u) => u.event))].length, clusters, doubled, resentEvents,
    clusterTimes: tss.length ? [new Date(tss[0]).toISOString(), new Date(tss[tss.length - 1]).toISOString()] : [], sample: uses.slice(0, 3) };
}

/// Asks the credit question for each subscribed speaker. Waits [waitS] for the
/// analytics service to send; one that never sends within it is a SKIP, not a
/// pass -- "nothing seen" is not "counted once".
async function checkCreditOnce(s, speakers, anchorIds, sinceTs, { waitS = 150 } = {}) {
  const deadline = Date.now() + waitS * 1000;
  const pending = new Map(speakers.map((p) => [p.name, p]));
  const out = {};
  while (pending.size && Date.now() < deadline) {
    for (const [n, p] of [...pending]) {
      const c = await creditsFor(p.token, p.userId, anchorIds, sinceTs).catch((e) => ({ error: e.message }));
      out[n] = c;
      if (c.uses > 0) pending.delete(n);
    }
    if (pending.size) await wait(10000);
  }
  // One more read after everything arrived: a second credit trails the first.
  await wait(15000);
  for (const p of speakers) out[p.name] = await creditsFor(p.token, p.userId, anchorIds, sinceTs).catch((e) => ({ error: e.message }));
  save('credits.json', out);
  for (const p of speakers) {
    const c = out[p.name];
    if (!c || c.error) { h.skipped(s, `${p.name}'s speaking time is credited exactly once`, `analytics room unreadable: ${c && c.error}`); continue; }
    if (c.uses === 0) {
      h.skipped(s, `${p.name}'s speaking time is credited exactly once`,
        `no construct uses for this call reached ${p.name}'s analytics room within ${waitS}s (${c.rooms} analytics room(s) read)`);
      continue;
    }
    h.check(s, `${p.name}'s speaking time is credited exactly once`, c.clusters === 1 && !c.doubled && c.resentEvents === 0,
      `${c.uses} uses in ${c.events} event(s) form ${c.clusters} separate credit(s)${c.doubled ? ' and every use appears an even number of times (sent twice)' : ''}${c.resentEvents ? `; ${c.resentEvents} event(s) repeat another's uses exactly` : ''}; times ${c.clusterTimes.join(' .. ')}`);
  }
  return out;
}

