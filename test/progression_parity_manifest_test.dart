// The client half of the Phase B progression parity gate (spec B.1.0).
//
// The star/Mission numbers a teacher acts on are produced twice — once here in
// Dart for the learner, once server-side in `admin-dash-api` for the teacher
// dashboard. A silent divergence between them is worse than an outage, so the
// two implementations are pinned to ONE set of test vectors.
//
// Those vectors are VENDORED, not shared: each repo owns a full, byte-identical
// copy, and there is no cross-repo import, submodule, or runtime fetch at test
// time. The checksum is the entire coupling mechanism:
//
//   * this test recomputes the sha256 of every vector file in THIS repo's
//     `test/fixtures/parity/progression/` and asserts it matches THIS repo's
//     committed `MANIFEST.sha256`, so a one-byte drift here turns THIS repo's CI
//     red — whether from corruption, a partial edit, or a fixture change landed
//     without regenerating the manifest;
//   * because both repos are expected to carry identical manifest CONTENT, a
//     vector changed on only one side leaves the two committed manifests
//     disagreeing, which is visible in review.
//
// The Python half is `admin-dash-api/tests/test_progression_parity_fixtures.py`;
// the manifest is generated by `admin-dash-api/tests/fixtures/parity/
// gen_progression_manifest.py` and copied here alongside the vectors it
// describes.
//
// Falsification: edit one byte of one fixture without regenerating the manifest
// and this test must fail.
//
// ---------------------------------------------------------------------------
// Why sha256 is implemented here rather than imported
// ---------------------------------------------------------------------------
// `package:crypto` is only a TRANSITIVE dependency of this app, and importing it
// would both trip `depend_on_referenced_packages` (flutter_lints) and create a
// hidden dependency. Adding it to `pubspec.yaml` is not an option this change can
// take. So the digest is computed inline, in ~60 lines of FIPS 180-4 SHA-256.
//
// This is a fixture-integrity checksum, not a security primitive, and its
// correctness is externally pinned rather than assumed: it must reproduce, byte
// for byte, a manifest that Python's `hashlib.sha256` and the system
// `shasum -a 256` independently produce. A wrong implementation cannot pass.

